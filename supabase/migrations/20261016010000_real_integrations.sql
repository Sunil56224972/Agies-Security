-- Real integrations: accounts, sensor API keys, NVD-backed CVE records,
-- ingest provenance and firewall enforcement state.

-- Accounts for the console. Passwords are scrypt hashes produced by the API server.
create table if not exists public.users (
  id              bigint generated by default as identity primary key,
  email           text not null unique,
  name            text not null,
  role            text not null check (role in ('admin','analyst','viewer')),
  password_hash   text not null,
  disabled        boolean not null default false,
  session_version integer not null default 1,
  created_at      timestamptz not null default now(),
  last_login_at   timestamptz
);

-- Keys used by sensors (ingest) and firewalls (feed pull). Only the SHA-256 is stored.
create table if not exists public.api_keys (
  id           bigint generated by default as identity primary key,
  name         text not null,
  prefix       text not null,
  hash         text not null unique,
  scopes       jsonb not null default '["ingest"]'::jsonb,
  created_by   text not null,
  created_at   timestamptz not null default now(),
  last_used_at timestamptz,
  revoked_at   timestamptz
);

-- CVE records synced from the NVD 2.0 API. cpe_matches is the NVD cpeMatch list.
alter table public.cves add column if not exists cpe_matches   jsonb not null default '[]'::jsonb;
alter table public.cves add column if not exists cvss_vector   text;
alter table public.cves add column if not exists kev           boolean not null default false;
alter table public.cves add column if not exists kev_added     date;
alter table public.cves add column if not exists published     timestamptz;
alter table public.cves add column if not exists last_modified timestamptz;
alter table public.cves add column if not exists source        text not null default 'curated';
alter table public.cves add column if not exists synced_at     timestamptz;
alter table public.cves alter column remediation drop not null;

-- Where an alert or asset came from (sensor rule id, import, manual).
alter table public.alerts add column if not exists external_ref text;
alter table public.assets add column if not exists source       text not null default 'manual';
alter table public.alerts drop constraint if exists alerts_dest_port_check;
alter table public.alerts add constraint alerts_dest_port_check check (dest_port between 0 and 65535);
create index if not exists alerts_status_idx on public.alerts (status, updated_at);

-- Enforcement result from the configured backend (feed, webhook, cloudflare, record).
-- packets_dropped was never measured by anything real, so it goes.
alter table public.firewall_rules add column if not exists enforcement jsonb;
alter table public.firewall_rules drop column if exists packets_dropped;

create index if not exists server_logs_logged_idx on public.server_logs (logged_at);
create index if not exists server_logs_client_idx on public.server_logs (client_ip);

alter table public.users    enable row level security;
alter table public.api_keys enable row level security;