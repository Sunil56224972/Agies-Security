-- Cases, approval queue and threat hunts.
-- Safe to re-run: every statement is idempotent.

-- ---- Cases -------------------------------------------------------------------
create table if not exists public.cases (
  case_id       text primary key,
  title         text not null check (char_length(title) between 4 and 200),
  description   text not null default '',
  severity      text not null default 'MEDIUM' check (severity in ('CRITICAL','HIGH','MEDIUM','LOW')),
  status        text not null default 'OPEN' check (status in ('OPEN','IN_PROGRESS','CONTAINED','CLOSED')),
  assignee_id   bigint references public.users(id) on delete set null,
  assignee_name text,
  tags          jsonb not null default '[]'::jsonb,
  mitre         jsonb not null default '[]'::jsonb,
  related       jsonb not null default '[]'::jsonb,
  resolution    text,
  escalated     boolean not null default false,
  escalated_at  timestamptz,
  source        text not null default 'manual',
  created_by    text not null,
  closed_at     timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists cases_status_idx on public.cases (status, updated_at desc);

create table if not exists public.case_alerts (
  id       bigint generated by default as identity primary key,
  case_id  text not null references public.cases(case_id) on delete cascade,
  alert_id text not null references public.alerts(alert_id) on delete cascade,
  added_by text not null,
  added_at timestamptz not null default now(),
  unique (case_id, alert_id)
);
create index if not exists case_alerts_alert_idx on public.case_alerts (alert_id);

create table if not exists public.case_tasks (
  id            bigint generated by default as identity primary key,
  case_id       text not null references public.cases(case_id) on delete cascade,
  title         text not null check (char_length(title) between 2 and 240),
  phase         text,
  status        text not null default 'TODO' check (status in ('TODO','DOING','DONE','SKIPPED')),
  assignee_name text,
  due_at        timestamptz,
  done_at       timestamptz,
  created_by    text not null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists case_tasks_case_idx on public.case_tasks (case_id, id);

create table if not exists public.case_iocs (
  id         bigint generated by default as identity primary key,
  case_id    text not null references public.cases(case_id) on delete cascade,
  type       text not null,
  value      text not null check (char_length(value) between 1 and 2048),
  note       text,
  verdict    text,
  score      integer,
  summary    text,
  checked_at timestamptz,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (case_id, value)
);

-- Comments, evidence, analyst timeline entries and system events in one stream.
create table if not exists public.case_events (
  id          bigint generated by default as identity primary key,
  case_id     text not null references public.cases(case_id) on delete cascade,
  kind        text not null check (kind in ('comment','evidence','timeline','event')),
  author      text not null,
  author_id   bigint references public.users(id) on delete set null,
  title       text,
  body        text not null check (char_length(body) between 1 and 20000),
  sha256      text,
  occurred_at timestamptz not null default now(),
  created_at  timestamptz not null default now()
);
create index if not exists case_events_case_idx on public.case_events (case_id, occurred_at);

-- ---- Approval queue -----------------------------------------------------------
create table if not exists public.approvals (
  approval_id      text primary key,
  action           text not null check (action in ('BLOCK','ISOLATE')),
  target_ip        text not null,
  reason           text not null,
  alert_id         text references public.alerts(alert_id) on delete set null,
  investigation_id text,
  case_id          text references public.cases(case_id) on delete set null,
  confidence       integer check (confidence between 0 and 100),
  route            text not null,
  status           text not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED','EXPIRED','FAILED')),
  requested_by     text not null,
  decided_by       text,
  decided_at       timestamptz,
  decision_note    text,
  rule_id          text,
  result           jsonb,
  ttl_hours        integer,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists approvals_status_idx on public.approvals (status, created_at desc);
create index if not exists approvals_inv_idx on public.approvals (investigation_id) where investigation_id is not null;

-- ---- Threat hunts ---------------------------------------------------------------
create table if not exists public.hunts (
  hunt_id        text primary key,
  name           text not null check (char_length(name) between 4 and 160),
  hypothesis     text not null,
  technique      text,
  criteria       jsonb not null default '{}'::jsonb,
  created_by     text not null,
  runs           integer not null default 0,
  last_run_at    timestamptz,
  last_hits      integer,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.hunt_runs (
  id          bigint generated by default as identity primary key,
  hunt_id     text references public.hunts(hunt_id) on delete cascade,
  name        text not null,
  run_by      text not null,
  hits        integer not null default 0,
  new_hits    integer,
  duration_ms integer not null default 0,
  summary     jsonb not null default '{}'::jsonb,
  findings    jsonb not null default '[]'::jsonb,
  created_at  timestamptz not null default now()
);
create index if not exists hunt_runs_hunt_idx on public.hunt_runs (hunt_id, created_at desc);

