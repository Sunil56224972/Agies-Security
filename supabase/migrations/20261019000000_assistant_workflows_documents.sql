-- Assistant threads, workflows, analyst decision feedback, analysed documents,
-- custom detection rules and Jira links on cases.
-- Safe to re-run: every statement is idempotent.

-- ---- AI assistant ------------------------------------------------------------
create table if not exists public.chat_threads (
  thread_id  text primary key,
  title      text not null default 'New conversation',
  user_id    bigint references public.users(id) on delete cascade,
  user_name  text not null,
  messages   jsonb not null default '[]'::jsonb,
  pending    jsonb,
  tokens     integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists chat_threads_user_idx on public.chat_threads (user_id, updated_at desc);

-- ---- Workflows -----------------------------------------------------------------
create table if not exists public.workflows (
  workflow_id text primary key,
  name        text not null check (char_length(name) between 3 and 120),
  description text not null default '',
  inputs      jsonb not null default '[]'::jsonb,
  steps       jsonb not null default '[]'::jsonb,
  enabled     boolean not null default true,
  created_by  text not null,
  runs        integer not null default 0,
  last_run_at timestamptz,
  last_status text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.workflow_runs (
  run_id      text primary key,
  workflow_id text not null,
  name        text not null,
  input       jsonb not null default '{}'::jsonb,
  status      text not null default 'RUNNING' check (status in ('RUNNING','SUCCEEDED','FAILED','PARTIAL')),
  steps       jsonb not null default '[]'::jsonb,
  run_by      text not null,
  duration_ms integer,
  finished_at timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists workflow_runs_wf_idx on public.workflow_runs (workflow_id, created_at desc);
create index if not exists workflow_runs_created_idx on public.workflow_runs (created_at desc);

-- ---- Decision feedback ---------------------------------------------------------------
create table if not exists public.decision_feedback (
  id               bigint generated by default as identity primary key,
  investigation_id text not null references public.investigations(investigation_id) on delete cascade,
  alert_id         text,
  engine           text,
  outcome          text not null,
  confidence       integer,
  correct          boolean not null,
  correct_outcome  text,
  rating           integer check (rating between 1 and 5),
  notes            text,
  analyst          text not null,
  analyst_id       bigint references public.users(id) on delete set null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create unique index if not exists decision_feedback_one_idx on public.decision_feedback (investigation_id, analyst);

-- ---- Documents -----------------------------------------------------------------------
create table if not exists public.documents (
  doc_id      text primary key,
  name        text not null,
  mime        text,
  size_bytes  integer not null,
  sha256      text not null,
  lines       integer not null default 0,
  content     text not null default '',
  truncated   boolean not null default false,
  iocs        jsonb not null default '[]'::jsonb,
  refs        jsonb not null default '{}'::jsonb,
  intel       jsonb,
  case_id     text references public.cases(case_id) on delete set null,
  uploaded_by text not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists documents_sha_idx on public.documents (sha256);

-- ---- Custom detection rules ------------------------------------------------------------
create table if not exists public.custom_rules (
  rule_id     text primary key,
  title       text not null,
  yaml        text not null check (char_length(yaml) between 10 and 60000),
  level       text not null default 'medium',
  technique   text,
  target      text,
  enabled     boolean not null default true,
  hits        integer not null default 0,
  last_hit_at timestamptz,
  created_by  text not null,
  updated_by  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---- Jira link on cases -------------------------------------------------------------
alter table public.cases add column if not exists jira jsonb;

-- ---- Access: API server only --------------------------------------------------------
alter table public.chat_threads      enable row level security;
alter table public.workflows         enable row level security;
alter table public.workflow_runs     enable row level security;
alter table public.decision_feedback enable row level security;
alter table public.documents         enable row level security;
alter table public.custom_rules      enable row level security;
revoke all on public.chat_threads, public.workflows, public.workflow_runs, public.decision_feedback, public.documents, public.custom_rules from anon, authenticated;
grant select, insert, update, delete on public.chat_threads, public.workflows, public.workflow_runs, public.decision_feedback, public.documents, public.custom_rules to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on all sequences in schema public from anon, authenticated;
-- ---- Restore support ------------------------------------------------------------------
-- A restore writes rows with their original identity ids; this moves each identity
-- sequence past the highest id so the next insert does not collide.
create or replace function public.aegis_sync_identity() returns void
language plpgsql security definer set search_path = public as $$
declare t text;
begin
  foreach t in array array['alert_notes','suppressions','case_alerts','case_tasks','case_iocs','case_events','hunt_runs','decision_feedback','server_logs','audit_log'] loop
    execute format('select setval(pg_get_serial_sequence(%L, %L), greatest(coalesce((select max(id) from public.%I), 0), 1))', 'public.' || t, 'id', t);
  end loop;
end $$;
revoke all on function public.aegis_sync_identity() from public, anon, authenticated;
grant execute on function public.aegis_sync_identity() to service_role;