-- Aegis Security schema for Supabase (Postgres 15+).
-- Apply with `supabase db push`, the SQL editor, or the Supabase MCP `apply_migration` tool.
-- Seed rows are inserted by the API server on first boot (src/seed.js), so this file is schema only.

create extension if not exists pgcrypto;

create table if not exists public.assets (
  ip_address        text primary key,
  hostname          text not null,
  os_family         text not null,
  os_version        text not null,
  owner             text,
  running_services  jsonb not null default '[]'::jsonb,
  installed_packages jsonb not null default '[]'::jsonb,
  criticality       text not null check (criticality in ('CRITICAL','HIGH','MEDIUM','LOW')),
  waf_enabled       boolean not null default false,
  last_scanned      timestamptz not null default now()
);

create table if not exists public.cves (
  cve_id              text primary key,
  title               text not null,
  cvss_score          numeric(3,1) not null,
  severity            text not null,
  affected_products   jsonb not null default '[]'::jsonb,
  vulnerable_versions text,
  exploit_vector      text,
  description         text not null,
  remediation         text not null,
  match_terms         jsonb not null default '[]'::jsonb
);

create table if not exists public.alerts (
  alert_id    text primary key,
  signature   text not null,
  category    text not null,
  severity    text not null check (severity in ('CRITICAL','HIGH','MEDIUM','LOW')),
  source_ip   text not null,
  dest_ip     text not null,
  dest_port   integer not null,
  protocol    text not null,
  sensor      text,
  raw_payload text not null,
  status      text not null default 'NEW'
              check (status in ('NEW','INVESTIGATING','CONFIRMED','CONTAINED','MITIGATED','FALSE_POSITIVE','CLOSED')),
  detected_at timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists alerts_detected_idx on public.alerts (detected_at desc);

create table if not exists public.server_logs (
  id             bigint generated by default as identity primary key,
  host_ip        text not null,
  log_type       text not null check (log_type in ('http_access','auth_log','edr_process','system')),
  status_code    integer,
  request_method text,
  request_uri    text,
  client_ip      text,
  raw_entry      text not null,
  logged_at      timestamptz not null default now()
);
create index if not exists server_logs_host_idx on public.server_logs (host_ip, logged_at desc);

create table if not exists public.investigations (
  investigation_id text primary key,
  alert_id         text not null references public.alerts(alert_id) on delete cascade,
  target_ip        text not null,
  attacker_ip      text not null,
  outcome          text not null check (outcome in ('ATTACK_SUCCEEDED','ATTACK_FAILED','FALSE_POSITIVE','RECON_ONLY')),
  confidence       integer not null check (confidence between 0 and 100),
  mitre_tactic     text,
  mitre_technique  text,
  summary          text not null,
  report           text,
  engine           text not null,
  steps            jsonb not null default '[]'::jsonb,
  actions_taken    jsonb not null default '[]'::jsonb,
  verification     jsonb,
  human_override   jsonb,
  duration_ms      integer,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists investigations_alert_idx on public.investigations (alert_id, created_at desc);

create table if not exists public.firewall_rules (
  rule_id          text primary key,
  target_ip        text not null,
  action           text not null check (action in ('BLOCK','ISOLATE')),
  reason           text not null,
  enacted_by       text not null,
  is_active        boolean not null default true,
  packets_dropped  bigint not null default 0,
  investigation_id text references public.investigations(investigation_id) on delete set null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists firewall_rules_target_idx on public.firewall_rules (target_ip) where is_active;

create table if not exists public.app_config (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_log (
  id         bigint generated by default as identity primary key,
  actor      text not null,
  action     text not null,
  target     text,
  detail     text,
  created_at timestamptz not null default now()
);
create index if not exists audit_log_created_idx on public.audit_log (created_at desc);

-- The browser never talks to Supabase directly; the API server uses the
-- service-role key, which bypasses RLS. Enabling RLS with no policies keeps
-- the anon key from reading or writing any of these tables.
alter table public.assets          enable row level security;
alter table public.cves            enable row level security;
alter table public.alerts          enable row level security;
alter table public.server_logs     enable row level security;
alter table public.investigations  enable row level security;
alter table public.firewall_rules  enable row level security;
alter table public.app_config      enable row level security;
alter table public.audit_log       enable row level security;