-- Case handling, suppression rules and rule expiry.
-- Safe to re-run: every statement is idempotent.

-- ---- Alerts: ownership and lifecycle timestamps -----------------------------
alter table public.alerts add column if not exists assignee_id     bigint references public.users(id) on delete set null;
alter table public.alerts add column if not exists assignee_name   text;
alter table public.alerts add column if not exists acknowledged_at timestamptz;
alter table public.alerts add column if not exists resolved_at     timestamptz;
alter table public.alerts add column if not exists suppressed_by   bigint;

create index if not exists alerts_assignee_idx on public.alerts (assignee_id) where assignee_id is not null;
create index if not exists alerts_source_ip_idx on public.alerts (source_ip);
create index if not exists alerts_dest_ip_idx on public.alerts (dest_ip);

-- Backfill before the trigger exists so history keeps its original times.
update public.alerts set acknowledged_at = updated_at where status <> 'NEW' and acknowledged_at is null;
update public.alerts set resolved_at = updated_at
 where status in ('CONTAINED','MITIGATED','FALSE_POSITIVE','CLOSED') and resolved_at is null;

-- Acknowledged = first time the alert leaves NEW. Resolved = entered a closed
-- status; reopening clears it. Explicit values from the API are kept.
create or replace function public.aegis_alert_lifecycle() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status <> 'NEW' and new.acknowledged_at is null then
    new.acknowledged_at := coalesce(case when tg_op = 'UPDATE' then old.acknowledged_at end, now());
  end if;
  if new.status in ('CONTAINED','MITIGATED','FALSE_POSITIVE','CLOSED') then
    if new.resolved_at is null then
      new.resolved_at := coalesce(case when tg_op = 'UPDATE' then old.resolved_at end, now());
    end if;
  else
    new.resolved_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists alerts_lifecycle on public.alerts;
create trigger alerts_lifecycle before insert or update of status, acknowledged_at, resolved_at on public.alerts
  for each row execute function public.aegis_alert_lifecycle();

-- ---- Analyst notes and case events -------------------------------------------
create table if not exists public.alert_notes (
  id         bigint generated by default as identity primary key,
  alert_id   text not null references public.alerts(alert_id) on delete cascade,
  author     text not null,
  author_id  bigint references public.users(id) on delete set null,
  kind       text not null default 'note' check (kind in ('note','event')),
  body       text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);
create index if not exists alert_notes_alert_idx on public.alert_notes (alert_id, created_at);

-- ---- Suppression (tuning) rules ---------------------------------------------
create table if not exists public.suppressions (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 3 and 120),
  signature   text,
  source_cidr text,
  dest_cidr   text,
  dest_port   integer check (dest_port between 0 and 65535),
  enabled     boolean not null default true,
  expires_at  timestamptz,
  hits        integer not null default 0,
  last_hit_at timestamptz,
  created_by  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint suppressions_has_condition check (signature is not null or source_cidr is not null or dest_cidr is not null or dest_port is not null)
);

do $$ begin
  alter table public.alerts add constraint alerts_suppressed_by_fkey
    foreign key (suppressed_by) references public.suppressions(id) on delete set null;
exception when duplicate_object then null; end $$;
create index if not exists alerts_suppressed_idx on public.alerts (suppressed_by) where suppressed_by is not null;

-- ---- Containment rule expiry ------------------------------------------------
alter table public.firewall_rules add column if not exists expires_at timestamptz;
create index if not exists firewall_rules_expiry_idx on public.firewall_rules (expires_at) where is_active and expires_at is not null;

-- ---- Access: API server only -------------------------------------------------
alter table public.alert_notes  enable row level security;
alter table public.suppressions enable row level security;
revoke all on public.alert_notes, public.suppressions from anon, authenticated;
grant select, insert, update, delete on public.alert_notes, public.suppressions to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on all sequences in schema public from anon, authenticated;
revoke execute on function public.aegis_alert_lifecycle() from public, anon, authenticated;